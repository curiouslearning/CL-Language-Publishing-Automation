import io
import os
import shutil
import threading
import time
import uuid
import zipfile

import lang_paths

# -------------------------------------------
# Generated language packages on the web page (spec 008).
# Which run (and which page session) produced each lang/<language>/ folder, the zip download,
# and - on the hosted page only - deleting a session's packages once that session has ended.
# Logic only: app.py does the Streamlit wiring and passes in how to tell a session is alive.
# All state is in-process: the generator runs as a single process (spec 005).
# -------------------------------------------


class Unavailable(Exception):
    """The package is no longer the one the run produced (replaced, being regenerated, or gone)."""


# lang key → {"owner_session", "run_id", "active", "inactive_since"}
_entries = {}
# Every language a run in THIS process has claimed. Cleanup only ever deletes these: a folder that was
# already there when the process started (e.g. a developer's lang/ with FTM_HOSTED=1 set) is never touched.
_claimed = set()
_lock = threading.Lock()
_janitor_started = False


def _key(lang):
    return lang.strip().lower()


def claim(lang, session_id):
    """A run is about to (re)build lang/<lang>/: it now belongs to this session and run."""
    run_id = uuid.uuid4().hex
    with _lock:
        previous = _entries.get(_key(lang))
        _claimed.add(_key(lang))
        _entries[_key(lang)] = {"owner_session": session_id, "run_id": run_id,
                                "active": True, "inactive_since": None, "previous": previous}
    return run_id


def finish(lang, run_id, touched=True):
    """
    The run has ended (any outcome). Only from now on may its package be downloaded or cleaned up.
    touched=False: the pipeline stopped before it wiped the folder, so the earlier owner keeps it.
    """
    with _lock:
        key = _key(lang)
        entry = _entries.get(key)
        if not entry or entry["run_id"] != run_id:
            return
        previous = entry.pop("previous", None)
        if touched:
            entry["active"] = False
        elif previous:
            _entries[key] = previous
        else:
            del _entries[key]  # a folder no run owns is an orphan: the hosted janitor removes it


def availability(lang, run_id, state):
    """'available' | 'regenerating' | 'replaced' | 'gone' for a finished run; None if it has no package."""
    if state not in ("complete", "warning") or not run_id:
        return None
    with _lock:
        entry = dict(_entries.get(_key(lang)) or {})
    if entry.get("active"):
        return "regenerating"
    if entry and entry["run_id"] != run_id:
        return "replaced"
    if not entry or not os.path.isdir(lang_paths.lang_dir(lang)) or not os.path.isfile(lang_paths.json_path(lang)):
        return "gone"
    return "available"


def owned_by(lang, session_id):
    """True if this session's last finished run produced lang/<lang>/ (hosted 'already generated' check)."""
    with _lock:
        entry = _entries.get(_key(lang))
        return bool(entry) and not entry["active"] and entry["owner_session"] == session_id


def build_zip(lang, run_id):
    """The package as one zip: <lang>/ftm_<lang>.json, <lang>/audios/…, <lang>/images/. mp3s aren't recompressed."""
    state = availability(lang, run_id, "complete")
    if state != "available":
        raise Unavailable(state)
    root = lang_paths.lang_dir(lang)
    top = os.path.basename(root)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_STORED) as zf:
        zf.writestr(f"{top}/", b"")
        zf.writestr(f"{top}/images/", b"")  # kept even when empty, like a local build
        for folder, _, files in os.walk(root, followlinks=False):
            for name in sorted(files):
                path = os.path.join(folder, name)
                if os.path.islink(path) or not os.path.isfile(path):
                    continue
                rel = os.path.relpath(path, root).replace(os.sep, "/")
                zf.write(path, f"{top}/{rel}")
    # Regenerated by someone else while zipping: don't hand out a mix of two runs
    if availability(lang, run_id, "complete") != "available":
        raise Unavailable("replaced")
    data = buffer.getvalue()
    buffer.close()
    return data


def _log(text):
    """Server log line (Cloud Logging). Never lets a console that can't print emoji stop a cleanup."""
    try:
        print(text, flush=True)
    except (UnicodeEncodeError, OSError):
        print(text.encode("ascii", "replace").decode("ascii"), flush=True)


def _remove(name, why):
    try:
        shutil.rmtree(os.path.join(lang_paths.LANG_ROOT, name))
        _log(f"🧹 Cleaned up lang/{name} ({why})")
        return True
    except FileNotFoundError:
        return True
    except OSError as e:
        _log(f"⚠ Cleanup failed for lang/{name}: {e}")
        return False


def sweep(is_alive, now, grace=60):
    """One cleanup pass (hosted only): delete packages whose session ended `grace` seconds ago, and orphans."""
    removed = []
    with _lock:
        for key, entry in list(_entries.items()):
            if entry["active"]:
                continue  # never under a running pipeline
            if is_alive(entry["owner_session"]):
                entry["inactive_since"] = None  # reconnected after a short drop
                continue
            if entry["inactive_since"] is None:
                entry["inactive_since"] = now
            if now - entry["inactive_since"] >= grace and _remove(key, "session ended"):
                del _entries[key]
                _claimed.discard(key)
                removed.append(key)
        # Folders a run in this process created but nobody owns any more (left after an error): nobody can
        # download them. Only languages claimed in this process: pre-existing folders are never deleted.
        for name in sorted(_claimed - set(_entries)):
            if not os.path.isdir(os.path.join(lang_paths.LANG_ROOT, name)):
                _claimed.discard(name)  # nothing left to clean
            elif _remove(name, "no owner"):
                _claimed.discard(name)
                removed.append(name)
    return removed


def start_janitor(is_alive, interval=15, grace=60):
    """Run sweep() every `interval` seconds on a daemon thread. Only the first call starts it."""
    global _janitor_started
    with _lock:
        if _janitor_started:
            return
        _janitor_started = True

    def loop():
        while True:
            try:
                sweep(is_alive, time.monotonic(), grace)
            except Exception as e:  # keep cleaning up after an unexpected error
                _log(f"⚠ Cleanup pass failed: {type(e).__name__}: {e}")
            time.sleep(interval)

    threading.Thread(target=loop, name="package-janitor", daemon=True).start()
